const encoder = new TextEncoder();

function toHex(value: ArrayBuffer) {
  return [...new Uint8Array(value)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

function constantTimeEqual(left: string, right: string) {
  if (left.length !== right.length) return false;
  let difference = 0;
  for (let index = 0; index < left.length; index += 1) difference |= left.charCodeAt(index) ^ right.charCodeAt(index);
  return difference === 0;
}

async function sha256(value: string) {
  return toHex(await crypto.subtle.digest('SHA-256', encoder.encode(value)));
}

async function validateTelegramInitData(initData: string, botToken: string): Promise<TelegramUser | null> {
  const params = new URLSearchParams(initData);
  const receivedHash = params.get('hash');
  const authDate = Number(params.get('auth_date') || 0);
  if (!receivedHash || !authDate) return null;
  const now = Math.floor(Date.now() / 1000);
  if (authDate > now + 300 || now - authDate > 86400) return null;
  const dataCheckString = [...params.entries()].filter(([key]) => key !== 'hash').sort(([left], [right]) => left.localeCompare(right)).map(([key, value]) => `${key}=${value}`).join('\n');
  const webAppDataKey = await crypto.subtle.importKey('raw', encoder.encode('WebAppData'), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const secretKey = await crypto.subtle.sign('HMAC', webAppDataKey, encoder.encode(botToken));
  const validationKey = await crypto.subtle.importKey('raw', secretKey, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const calculatedHash = toHex(await crypto.subtle.sign('HMAC', validationKey, encoder.encode(dataCheckString)));
  if (!constantTimeEqual(calculatedHash, receivedHash.toLowerCase())) return null;
  try {
    const user = JSON.parse(params.get('user') || 'null') as TelegramUser | null;
    return user?.id && user.first_name ? user : null;
  } catch { return null; }
}

function publicUser(user: SessionUser) {
  return { id: user.id, name: user.name, role: user.role, username: user.username, photoUrl: user.photo_url };
}

async function getCurrentUser(request: NextRequest): Promise<SessionUser | null> {
  const token = request.cookies.get(sessionCookie)?.value;
  if (!token) return null;
  const tokenHash = await sha256(token);
  return db.prepare('SELECT staff.id, staff.name, staff.role, staff.telegram_id, staff.username, staff.photo_url FROM sessions JOIN staff ON staff.id = sessions.staff_id WHERE sessions.token_hash = ? AND sessions.expires_at > ? AND staff.active = 1').bind(tokenHash, new Date().toISOString()).first<SessionUser>();
}

async function getEmployeeAccessCode(isLocal: boolean) {
  const stored = await db.prepare("SELECT value FROM app_settings WHERE key = 'employee_access_code'").first<{ value: string }>();
  return stored?.value || runtimeEnv.EMPLOYEE_ACCESS_CODE || process.env.EMPLOYEE_ACCESS_CODE || (isLocal ? '1111' : '');
}

