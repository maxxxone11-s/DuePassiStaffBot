async function ensureDishColumns(db: AppDatabase) {
  const info = await db.prepare('PRAGMA table_info(dishes)').all<{ name: string }>();
  const columns = new Set(info.results.map((column) => column.name));
  if (!columns.has('category')) await db.prepare("ALTER TABLE dishes ADD COLUMN category TEXT NOT NULL DEFAULT 'crudo'").run();
  if (!columns.has('weight')) await db.prepare('ALTER TABLE dishes ADD COLUMN weight INTEGER NOT NULL DEFAULT 0').run();
  if (!columns.has('photo')) await db.prepare("ALTER TABLE dishes ADD COLUMN photo TEXT").run();
  if (!columns.has('recipe')) await db.prepare("ALTER TABLE dishes ADD COLUMN recipe TEXT NOT NULL DEFAULT 'null'").run();
  if (!columns.has('components')) await db.prepare("ALTER TABLE dishes ADD COLUMN components TEXT NOT NULL DEFAULT '{}'").run();
}

async function ensureStaffColumns(db: AppDatabase) {
  const info = await db.prepare('PRAGMA table_info(staff)').all<{ name: string }>();
  const columns = new Set(info.results.map((column) => column.name));
  if (!columns.has('telegram_id')) await db.prepare('ALTER TABLE staff ADD COLUMN telegram_id TEXT').run();
  if (!columns.has('username')) await db.prepare('ALTER TABLE staff ADD COLUMN username TEXT').run();
  if (!columns.has('photo_url')) await db.prepare('ALTER TABLE staff ADD COLUMN photo_url TEXT').run();
  if (!columns.has('last_seen_at')) await db.prepare('ALTER TABLE staff ADD COLUMN last_seen_at TEXT').run();
  if (!columns.has('active')) await db.prepare('ALTER TABLE staff ADD COLUMN active INTEGER NOT NULL DEFAULT 1').run();
}

let initialization: Promise<void> | undefined;

function initDb() {
  initialization ??= initializeDb().catch((error) => {
    initialization = undefined;
    throw error;
  });
  return initialization;
}

